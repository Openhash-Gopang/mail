/** 호출 입력을 채워 완성된 system 프롬프트를 만든다. ctx: { lang, chapter({n,title,text}|null), escalated(bool), chapters([{n,title,text}]) } */
export function composeSP(ctx) {
  ctx = ctx || {};
  const lang = LANG_NAME[ctx.lang] || LANG_NAME.ko;
  const cur = ctx.chapter ? '사용법 ' + ctx.chapter.n + '장 · ' + ctx.chapter.title + '\n' + String(ctx.chapter.text).slice(0, 1500) : '(지금 보는 장 없음)';
  const ex = (ctx.chapters && ctx.chapters.length)
    ? ctx.chapters.map((c) => '[사용법 ' + c.n + '장 · ' + c.title + ']\n' + String(c.text).slice(0, 1100)).join('\n\n')
    : '(이 질문과 겹치는 매뉴얼 장을 찾지 못했습니다.)';
  return SP_TEXT.split('{화면 언어}').join(lang).split('{지금 보는 장}').join(cur).split('{관리자 질의 여부}').join(ctx.escalated ? '예' : '아니오').split('{매뉴얼 발췌}').join(ex);
}
